const c = (
  id,
  title,
  focus,
  prompt,
  code,
  bugLine,
  fixes,
  correctFix,
  hint,
  explanation,
) => {
  // Keep the correct answer in a stable but varied position. A predictable
  // first-option answer would teach guessing rather than debugging.
  const rotation =
    Array.from(id).reduce((sum, character) => sum + character.charCodeAt(0), 0) %
    fixes.length;
  const rotatedFixes = fixes.map(
    (_, index) => fixes[(index - rotation + fixes.length) % fixes.length],
  );

  return {
    id,
    title,
    focus,
    prompt,
    goal: CHALLENGE_GOALS[id] || prompt,
    code,
    bugLine,
    fixes: rotatedFixes,
    fixFeedback: rotatedFixes.map(
      (fix) => FIX_FEEDBACK[id]?.[fix.trim()] || null,
    ),
    correctFix: (correctFix + rotation) % fixes.length,
    hint,
    explanation,
  };
};

